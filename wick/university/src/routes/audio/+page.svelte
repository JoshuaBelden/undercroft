	</li>
	<li>
		<strong>Occlusion</strong>: raycast from listener to source in your physics, and drive
		<code>setMuffle</code> from how much is in the way. For per-source occlusion, add your own
		<code>BiquadFilterNode</code> between the source and the bus.
	</li>
	<li>
		<strong>Different rooms</strong>: blend <code>setReverb</code> toward each area's size. For
		truly different acoustics, build extra <code>ConvolverNode</code>s with measured IRs on
		<code>audio.audioContext</code> and crossfade their sends.
	</li>
	<li>
		<strong>Streaming music</strong>: for long tracks, play an <code>&lt;audio&gt;</code> element
		through
		<code>audioContext.createMediaElementSource()</code> into a dry bus, so it is never fully decoded
		into memory.
	</li>
	<li>
		<strong>Anything else</strong>: <code>load()</code> and <code>playBuffer()</code> /
		<code>playBufferAt()</code> take any buffer on any bus, and <code>audioContext</code> exposes the
		context for nodes of your own.
	</li>
</ul>

