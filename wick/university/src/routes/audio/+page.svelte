<h1>Audio</h1>
<p class="lede">
	<code>@wick/audio</code> is a game audio layer on the Web Audio API. It plays recordings by id on mixing
	buses, filters and reverberates them for the space they're in, and places them in 3D around the listener.
</p>

<h2>What it solves</h2>
<p>
	The Web Audio API gives you low-level building blocks: sources, filters, gain stages, panners. A
	game needs a structure built from them:
</p>
<ul>
	<li>
		<strong>Mixing.</strong> Independent volume for groups of sounds (music, ambience, effects), and a
		master volume over all of them.
	</li>
	<li>
		<strong>Environment.</strong> A sound behind a wall or underwater loses its high frequencies, and
		in a large stone hall it rings on after it stops.
	</li>
	<li>
		<strong>Spatialization.</strong> A sound has a direction and a distance relative to the listener.
	</li>
	<li>
		<strong>Asset indirection.</strong> Game code asks for <code>'door.open'</code>, not a file URL.
		Variants, pitch and volume are data.
	</li>
	<li>
		<strong>Accessibility.</strong> Text captions for audible sounds, and a mono mix.
	</li>
</ul>

<h2>The platform: the Web Audio API</h2>
<h3>An audio graph, rendered off the main thread</h3>
<p>
	Everything happens inside an <code>AudioContext</code>. You build a directed graph of
	<code>AudioNode</code>s: sources, processors such as filters, gains, panners and convolvers, and
	one destination, the speakers. JavaScript only builds and configures the graph. The browser
	renders it on a separate real-time audio thread, in blocks of 128 sample-frames (a
	<em>render quantum</em>), at the context's sample rate (typically 44.1 or 48 kHz). That's why
	audio keeps playing smoothly while the main thread is busy, and why you control nodes through
	parameters rather than by touching samples.
</p>
<Code code={rawGraph} label="the bare API" />

<h3>Buffers and sources</h3>
<ul>
	<li>
		<code>decodeAudioData</code> decodes a whole compressed file (Opus, MP3, AAC) into an
		<code>AudioBuffer</code>: uncompressed 32-bit float samples per channel, held in memory. Thirty
		seconds of 48 kHz stereo is 30 × 48 000 × 2 × 4 bytes, about 11.5 MB. Decoded buffers suit short
		sounds. Long music can stream through a <code>MediaElementAudioSourceNode</code> instead (see Extending).
	</li>
	<li>
		An <code>AudioBufferSourceNode</code> plays a buffer exactly once. You can't restart it, so you create
		a new one per play. They're cheap, and the browser frees them when they finish.
	</li>
	<li>
		<code>loop</code>, <code>loopStart</code> and <code>loopEnd</code> repeat a region of the buffer.
	</li>
	<li>
		<code>playbackRate</code> resamples, which changes speed and pitch together. 2 is an octave up,
		and one semitone is a factor of 2<sup>1/12</sup> ≈ 1.059.
	</li>
</ul>

<h3>Gain and decibels</h3>
<p>
	A <code>GainNode</code> multiplies each sample by its <code>gain</code>, so volume is linear
	amplitude. Loudness is perceived roughly logarithmically, so audio engineers work in decibels: dB
	= 20 · log<sub>10</sub>(gain). A gain of 0.5 is about −6 dB, 0.1 is −20 dB, and 0 is silence (−∞
	dB). WICK takes linear gains; mapping a slider through a dB curve is a choice for the game (see
	Extending).
</p>

<h3>Parameter automation, and why values ease</h3>
<p>
	Node parameters (<code>AudioParam</code>s: gain, frequency, playback rate) can be set directly or
	scheduled to change over time. A sudden jump in gain puts a discontinuity in the waveform, which
	is heard as a click (rapid jumps become "zipper noise"). So WICK eases every change with
	<code>setTargetAtTime</code>, an exponential approach with time constant τ. The browser computes
	it per sample on the audio thread, so it is smooth and exactly timed.
</p>
<Code code={automation} />

<h3>Autoplay policy</h3>
<p>
	Browsers don't let a page make sound until the user has interacted with it. An
	<code>AudioContext</code> created before that starts in the <code>suspended</code> state, and
	<code>resume()</code> only succeeds during a user gesture (a click, tap or key press).
	<code>AudioManager.unlock()</code> wraps this: call it from your first input handler.
</p>

<h2>Mixing: category buses</h2>
<p>
	A <em>bus</em> is a mixing-console idea: a channel that many sources feed into, with one fader for
	all of them. WICK makes one <code>GainNode</code> per category you name, and every category bus
	feeds a <code>master</code> bus. A sound plays through its own gain node (its per-play volume), optionally
	a panner, then its category's bus. Changing a category's volume is one parameter change, however many
	sounds are playing.
</p>
<SignalChain />
<p>
	Categories are either <strong>world</strong> or <strong>dry</strong>. World buses pass through the
	environment chain: the low-pass filter, and a send to the reverb. Dry buses (<code>dry</code> in the
	config) go straight to master, for sounds that aren't in the scene, such as music, interface sounds
	or narration. Music shouldn't turn muffled because the player's head went underwater.
</p>

<h2>Muffling: a low-pass filter</h2>
<h3>Why high frequencies are what you lose</h3>
<p>
	When sound passes through or around obstacles, high frequencies lose energy faster than low ones.
	Materials and water absorb short wavelengths more strongly, while long wavelengths diffract around
	obstacles and pass through walls. That's why music through a wall is mostly bass, and why
	everything underwater sounds dull. Attenuating the high frequencies imitates all of these:
	occlusion, obstruction, submersion, a tight padded space.
</p>
<h3>The filter</h3>
<p>
	A <em>low-pass</em> filter passes frequencies below its cutoff and attenuates those above. WICK
	uses a
	<code>BiquadFilterNode</code> of type <code>lowpass</code>. A biquad is a second-order recursive
	(IIR) filter, cheap to run and the standard building block of audio EQ. A second-order low-pass is
	flat below the cutoff, −3 dB at it, and falls 12 dB per octave above it. The diagram shows that
	idealized response; Web Audio's default <code>Q</code> adds a slight bump near the cutoff.
</p>
<FilterResponse />
<h3>A logarithmic sweep</h3>
<p>
	<code>setMuffle(amount)</code> maps 0–1 onto a cutoff from 20 kHz down to 500 Hz. Pitch perception is
	logarithmic, since each octave doubles the frequency, so the cutoff is interpolated in log space. A
	linear mapping would spend most of the range above 5 kHz, where the change is barely audible, then collapse
	at the end. The cutoff then eases toward its target with τ = 80 ms.
</p>
<Code code={muffleMath} />

<h2>Reverb: convolution with an impulse response</h2>
<h3>What reverberation is</h3>
<p>In a room, you hear a sound three ways:</p>
<ul>
	<li>
		<strong>The direct sound</strong>, straight from the source.
	</li>
	<li>
		<strong>Early reflections</strong>, the first distinct echoes off nearby surfaces, roughly
		within the first 50–80 ms. Your brain uses them to judge the room's size and shape.
	</li>
	<li>
		<strong>Late reverberation</strong>, thousands of reflections so dense they merge into a smooth
		tail that decays exponentially.
	</li>
</ul>
<p>
	A room's <em>RT60</em> is how long that tail takes to fall by 60 dB. It's under half a second for a
	furnished room, and several seconds for a cathedral or a cave. Reverb tells the player how big the space
	is and what it's made of. The ratio of reverberant to direct sound is also a distance cue.
</p>
<h3>Convolution</h3>
<p>
	A room (an ideal one, at least) behaves as a <em>linear time-invariant</em> system: its response
	to any sound is fully described by its response to a single instantaneous click, the
	<em>impulse response</em> (IR). Convolving any dry signal with that IR yields the signal as heard in
	the room. Each input sample sets off a scaled, delayed copy of the whole IR, and the copies sum.
</p>
<Code code={convolutionMath} />
<p>
	Done directly, that's expensive. A 2.8 s IR at 48 kHz is 134 400 multiply-adds per output sample,
	about 6.5 billion per second per channel. The <code>ConvolverNode</code> instead does it in the
	frequency domain with the FFT, using partitioned convolution: it splits the IR into blocks so
	latency stays low and the cost drops to a few operations per sample per block. With its default
	<code>normalize: true</code>, the browser also scales the IR so that rooms of different length
	come out at similar loudness.
</p>
<h3>Where impulse responses come from</h3>
<p>
	IRs are usually <em>measured</em>. You fire a starter pistol or pop a balloon in a real space, or
	play a sine sweep and deconvolve it, and record the result. WICK <em>computes</em> one instead:
	stereo white noise under an exponential envelope. Noise with an exponential decay is a good model
	of a diffuse late tail. Independent noise in each channel makes it wide, since the left and right
	tails are decorrelated. The envelope <code>e<sup>−2.4t</sup></code> falls by 60 dB in ln(1000) / 2.4
	≈ 2.9 s, a stone room's RT60. The first 80 ms are reduced, so the dry sound stays clear before the tail
	builds. The IR shapes how the reverb rings, but you never hear it on its own.
</p>
<ImpulseResponse />
<h3>Send and return</h3>
<p>
	Rather than put the reverb inline, world buses <em>send</em> a copy of their signal to it through
	a gain node, the send level (<code>setReverb</code>, up to a wet level of 0.9, τ = 0.3 s). The dry
	signal carries on unchanged. That's the standard aux-send layout from mixing consoles: one shared
	reverb for all world sounds, with the wet/dry ratio set in one place. The reverb's output returns
	<em>through the muffler</em>, so a muffled space also has a muffled echo.
</p>

<h2>Spatial audio: HRTF panning and distance</h2>
<h3>How we hear direction</h3>
<p>Three cues tell us where a sound comes from:</p>
<ul>
	<li>
		<strong>Interaural time difference (ITD).</strong> A sound to your left reaches your left ear first,
		by up to about 0.7 ms.
	</li>
	<li>
		<strong>Interaural level difference (ILD).</strong> Your head shadows the far ear, mostly at high
		frequencies.
	</li>
	<li>
		<strong>Spectral cues.</strong> The folds of the outer ear (the pinna) filter sound differently depending
		on its direction. This is how we tell front from back and judge elevation, which time and level differences
		alone can't do.
	</li>
</ul>
<p>
	A <em>head-related transfer function</em> (HRTF) captures all three: a pair of filters, one per ear,
	measured for each direction around a listener's head. Running a sound through the HRTF for a direction
	makes it seem to come from there, and works best on headphones.
</p>
<h3>The panner</h3>
<p>
	<code>playBufferAt</code> inserts a <code>PannerNode</code> with
	<code>panningModel: 'HRTF'</code>. The browser filters the sound through its built-in, measured
	HRTF set for the direction between the listener and the source. The cheaper
	<code>'equalpower'</code> model only balances left against right, with no front/back or elevation.
</p>
<p>
	The listener is the context's <code>AudioListener</code>: a position, a forward vector and an up
	vector. The coordinate system is right-handed with +Y up, and the default forward is −Z, the same
	as a Three.js camera, so you can pass the camera's position and world direction straight to
	<code>setListener</code> every frame.
</p>
<h3>Distance attenuation</h3>
<p>
	WICK uses the <code>inverse</code> distance model, with distance <code>d</code> clamped between
	<code>refDistance</code> and <code>maxDistance</code>:
	<code>gain = refDistance / (refDistance + rolloff · (d − refDistance))</code>. With rolloff 1,
	that's
	<code>refDistance / d</code>: −6 dB each time the distance doubles, the inverse-distance law for
	sound pressure in open air. Defaults are full volume within 1.5 m (settable per sound) and no
	quieter past 60 m. <code>distanceGain()</code> computes the same curve in JavaScript, for decisions
	such as whether a sound is loud enough to caption.
</p>

<h2>The output stage: mono and background muting</h2>
<ul>
	<li>
		<strong>Mono.</strong> After master comes a gain node used as a downmixer. A node's
		<code>channelCount</code>, <code>channelCountMode</code> and <code>channelInterpretation</code>
		decide how inputs are up- or down-mixed. Setting it to one channel with
		<code>'speakers'</code> interpretation folds stereo to mono as M = ½ (L + R), and the destination
		then plays M on both speakers. This helps players with hearing in one ear, or one earbud in, who would
		otherwise miss hard-panned sounds.
	</li>
	<li>
		<strong>Background muting.</strong> A second gain node ramps to 0 while the page is hidden (the
		Page Visibility API: <code>document.hidden</code>, <code>visibilitychange</code>) or the window
		loses focus. The package listens for those events itself.
	</li>
</ul>
<p>
	Both come from your <code>options()</code> function, and <code>applyAudioOptions()</code> makes every
	live manager re-read it.
</p>

<h2>Playing sounds by id: the sound bank</h2>
<PlayFlow />
<ul>
	<li>
		<strong>A registry, not URLs.</strong> A <code>SoundDef</code> describes a sound: its recording
		ids, category, volume, optional base <code>rate</code> and random <code>variation</code>, and
		optional
		<code>caption</code>. The catalog's <code>files</code> maps recording ids to URLs, usually generated
		by an asset build that hashes file names for caching. Game code only ever names ids.
	</li>
	<li>
		<strong>Variation.</strong> Hearing an identical sample over and over (the "machine-gun effect")
		quickly sounds artificial. A recording id can have several variant files, and one is picked at
		random each play. <code>variation</code> also randomizes the playback rate, so ±6% gives a little
		pitch and timing spread.
	</li>
	<li>
		<strong>Lazy loading.</strong> A sound's variants are fetched and decoded on its first play, then
		kept. The decode is cached per URL, so variants shared between sounds load once.
	</li>
	<li>
		<strong>Missing recordings are not errors.</strong> A sound with no file, or no URLs, resolves to
		no buffers and plays nothing, and a loop of one returns a silent handle. You can wire a sound into
		the game before its recording exists, and a build report can list which ids are still missing.
	</li>
	<li>
		<strong>Loops with an intro.</strong> <code>loopStarts</code> maps a URL to a time. The source
		plays from 0 once, then loops between that time and the end (<code>loopStart</code>/<code
			>loopEnd</code
		>).
	</li>
</ul>
<h3>Captions</h3>
<p>
	For players who can't hear, or have the sound off, captions describe what they would have heard:
</p>
<ul>
	<li>
		<strong>When.</strong> A sound with a <code>caption</code> raises a cue when its effective level (per-play
		volume × its volume × distance falloff) is at least 0.04. That's the same falloff the panner applies,
		so a sound is captioned about as far away as it can be heard.
	</li>
	<li>
		<strong>With sound off.</strong> Cues are raised before the "is audio unlocked" check, so captions
		work even then.
	</li>
	<li>
		<strong>Loops.</strong> A loop re-raises its caption at most every 0.5 s while its volume keeps being
		set.
	</li>
	<li>
		<strong>Direction</strong> comes from projecting the vector to the source onto the listener's forward
		and right vectors.
	</li>
</ul>
