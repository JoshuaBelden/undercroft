<h2>Fading loops</h2>
<p>
	Beds and music come and go with game state, which makes them easy to get wrong. A naive version
	starts a second copy if the state flips twice during a load, or keeps playing after the state has
	moved on. <code>FadingLoop</code> handles this:
</p>
<ul>
	<li>
		<strong>Idempotent.</strong> You call <code>setWanted(bool)</code> as often as you like (every frame
		is fine); only a change acts.
	</li>
	<li>
		<strong>Gated.</strong> It waits for <code>allow()</code>, meaning audio is unlocked, before it
		starts anything.
	</li>
	<li>
		<strong>Fades rather than restarts.</strong> Wanted again mid-fade-out, it fades back up without restarting
		the loop.
	</li>
	<li>
		<strong>Safe against slow loads.</strong> Loading is asynchronous, so every change bumps a
		<em>generation</em> counter. When a load resolves, it compares the generation it started with against
		the current one, and stops its loop at once if anything changed in between. This is a general way
		to discard stale async results.
	</li>
</ul>

