/**
 * Turns raw interface art (art/images/*.png, *.jpg, *.webp) into WebP in static/assets/images, keeping
 * each file's name. Run with `pnpm asset:images`. See docs/dev/asset-pipeline.md.
 *
 * Then writes src/lib/content/images.generated.ts: each built picture's content hash, which
 * `imageUrl()` puts on its URL so a rebuilt picture is never shown from an old cached copy.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'art', 'images');
const OUT_DIR = path.join(ROOT, 'static', 'assets', 'images');
const MANIFEST = path.join(ROOT, 'src', 'lib', 'content', 'images.generated.ts');
/** Nothing is shown wider than this; larger sources are scaled down. */
const MAX_WIDTH = 2560;
const QUALITY = 82;

if (!existsSync(SOURCE_DIR)) {
	console.error(`No ${path.relative(ROOT, SOURCE_DIR)} folder: nothing to build.`);
	process.exit(1);
}
mkdirSync(OUT_DIR, { recursive: true });

for (const file of readdirSync(SOURCE_DIR)) {
	if (!/\.(png|jpe?g|webp)$/i.test(file)) continue;
	const out = path.join(OUT_DIR, `${path.parse(file).name}.webp`);
	const info = await sharp(path.join(SOURCE_DIR, file))
		.resize({ width: MAX_WIDTH, withoutEnlargement: true })
		.webp({ quality: QUALITY })
		.toFile(out);
	const kb = Math.round(statSync(out).size / 1024);
	console.log(`${file} -> ${path.relative(ROOT, out)} (${info.width}x${info.height}, ${kb} KB)`);
}

// Every picture in the folder, built just now or not, so the list is always complete.
const versions: Record<string, string> = {};
for (const file of readdirSync(OUT_DIR).sort()) {
	if (!file.endsWith('.webp')) continue;
	const hash = createHash('sha256').update(readFileSync(path.join(OUT_DIR, file)));
	versions[path.parse(file).name] = hash.digest('hex').slice(0, 8);
}
const source = `// Generated by scripts/build-images.ts (pnpm asset:images). Do not edit.

/** Picture name (static/assets/images, no extension) -> hash of its contents. */
export const IMAGE_VERSIONS: Record<string, string> = ${JSON.stringify(versions)};
`;
const config = await prettier.resolveConfig(MANIFEST);
writeFileSync(MANIFEST, await prettier.format(source, { ...config, filepath: MANIFEST }));
console.log(
	`Wrote ${Object.keys(versions).length} picture versions -> ${path.relative(ROOT, MANIFEST)}`
);
