/**
 * Map kit and layout types, shared by client and server.
 *
 * Coordinates are Three.js world space: +X east, +Y up, +Z south (north is -Z).
 * Distances are metres. The grid is CELL x CELL horizontally and LEVEL_HEIGHT vertically.
 */

export type Vec3 = [number, number, number];
export type Quat = [number, number, number, number];

/** Side of a grid cell. n = -Z, e = +X, s = +Z, w = -X. */
export type Edge = 'n' | 'e' | 's' | 'w';

/** A standard opening on a piece's footprint boundary. */
export interface PieceSocket {
	/** Opening type (`hall` now; `crawl`, `squeeze`, `canal` later). Only equal types connect. */
	type: string;
	/** Footprint cell the opening belongs to, [x, z] from the piece's north-west cell. */
	cell: [number, number];
	/** Level the opening's floor is on, 0 = the piece's lowest level. */
	level: number;
	edge: Edge;
}

/** Oriented collision box in piece space. */
export interface ColliderBox {
	center: Vec3;
	halfExtents: Vec3;
	rotation: Quat;
}

/** Gameplay volume in piece space, e.g. kind 'water'. */
export interface VolumeBox extends ColliderBox {
	kind: string;
}

/** A possible place for a loot crate, in piece space. */
export interface CrateMarker {
	/** Floor centre of the crate. */
	position: Vec3;
	/** Turn about +Y (radians). At 0 the crate's back is to the north (-Z). */
	yaw: number;
}

/** A modular piece exported from Blender. Generated by `pnpm asset:build`. */
export interface PieceDef {
	name: string;
	url: string;
	/** Footprint in cells, [x, z] before rotation. [0, 0] for caps, which occupy no cell. */
	footprint: [number, number];
	levels: number;
	sockets: PieceSocket[];
	spawns: Vec3[];
	/** Where creatures may start (creature-* markers). */
	creatures: Vec3[];
	extracts: Vec3[];
	/** Where the rite can be initiated (rite-* markers). */
	rites: Vec3[];
	/** Where a loot crate may stand (crate-* markers). The server fills only some of them. */
	crates: CrateMarker[];
	colliders: ColliderBox[];
	/** Gameplay volumes such as swimmable water (vol-<kind>-* boxes). */
	volumes: VolumeBox[];
	triangles: number;
}

/**
 * start: the expedition start room. major: one of the static major rooms, all placed on the
 * main route. connector: passages and minor rooms. end: dead ends that close branches.
 * cap: seals an unused opening without occupying a cell.
 */
export type PieceRole = 'start' | 'major' | 'connector' | 'end' | 'cap';

/** Gameplay data for a piece (hand-authored, in `src/lib/content/map/kit.ts`). */
export interface KitEntry {
	role: PieceRole;
	/** Relative chance when picking among pieces of the same role. */
	weight?: number;
	/** Caps: the socket type this piece seals. */
	seals?: string;
	/** Start rooms: piece always attached to the start room's opening. */
	exit?: string;
	/** Changes level: only ever attached by its highest socket, so it always leads down. */
	descends?: boolean;
	/** Major rooms: placed last on the main route, after a descent, so it is the deepest. */
	final?: boolean;
	/** Name shown in the room banner when a player first enters it. */
	title?: string;
	/** How the space sounds (reverb, damping); default 'tunnel'. See src/lib/content/audio/ambience.ts. */
	acoustics?: Acoustics;
}

export type Acoustics = 'tight' | 'tunnel' | 'hall' | 'vast';

export type MapKit = Record<string, KitEntry>;

/** One piece placed in the world. */
export interface Placement {
	piece: string;
	/** World position of the piece origin (floor level, centre of footprint). */
	position: Vec3;
	/** Quarter turns around +Y (counter-clockwise seen from above), 0-3. */
	rotation: number;
}

/** A loot crate standing in the map. */
export interface CratePlacement {
	id: string;
	/** Floor centre, world space. */
	position: Vec3;
	/** Turn about +Y (radians). At 0 its back is to the north (-Z) and it opens to the south. */
	yaw: number;
	/** The dev crate in the start room: only there in dev mode, and filled like the deepest. */
	debug?: boolean;
}

export interface MapLayout {
	seed: number;
	placements: Placement[];
	/** Loot crates (see docs/dev/items.md). Solid: they are part of the collision world. */
	crates: CratePlacement[];
}
