/**
 * Map kit and layout types, shared by client and server.
 *
 * Coordinates are Three.js world space: +X east, +Y up, +Z south (north is -Z).
 * Distances are metres. The grid is CELL x CELL horizontally and LEVEL_HEIGHT vertically.
 */

import type { LootableId } from '../../content/lootables.ts';

export type Vec3 = [number, number, number];
export type Quat = [number, number, number, number];

/** Side of a grid cell. n = -Z, e = +X, s = +Z, w = -X. */
export type Edge = 'n' | 'e' | 's' | 'w';

/** A standard opening on a piece's footprint boundary. */
export interface PieceSocket {
	/**
	 * Opening type. Only equal types connect. `hall` is the standard 2 m arch; `gate` is the 3.2 m
	 * double-door opening between an extraction room and the long stair down to the next level.
	 */
	type: string;
	/** Footprint cell the opening belongs to, [x, z] from the piece's north-west cell. */
	cell: [number, number];
	/** Level the opening's floor is on, 0 = the piece's lowest level. */
	level: number;
	edge: Edge;
}

/** Oriented collision box in piece space. */
export interface ColliderBox {
	center: Vec3;
	halfExtents: Vec3;
	rotation: Quat;
}

/** Gameplay volume in piece space, e.g. kind 'water'. */
export interface VolumeBox extends ColliderBox {
	kind: string;
}

/** A possible place for a loot crate, in piece space. */
export interface CrateMarker {
	/** Floor centre of the crate. */
	position: Vec3;
	/** Turn about +Y (radians). At 0 the crate's back is to the north (-Z). */
	yaw: number;
}

/** A lootable-<type>-<n> marker: a crate marker for one kind of lootable (docs/dev/lootables.md). */
export interface LootableMarker extends CrateMarker {
	type: LootableId;
}

/** A rope hanging straight down from `top` (rope-* markers), in piece space. See docs/dev/rope.md. */
export interface RopeMarker {
	top: Vec3;
	/** Metres it hangs. */
	length: number;
	/** An extraction rope: climbing this far up from its foot gets you out of the catacomb. */
	exit?: number;
}

/**
 * Where a rope can be tied at the top of a drop (anchor-* markers), in piece space: the tie point
 * on the ledge, and which way the drop is. See docs/dev/rope.md.
 */
export interface AnchorMarker {
	/** On the ledge floor at its edge, where the rope is tied. */
	position: Vec3;
	/** Turn about +Y (radians) of the way out over the drop; at 0 it is north (-Z). */
	yaw: number;
	/**
	 * A rope already tied here, for good (the start room's way down): metres from where a
	 * climber's hands reach at the top down to where their feet are at its end. Nobody unties it,
	 * and when it ends above the floor, climbing off the end is a drop.
	 */
	rope?: number;
}

/** A modular piece exported from Blender. Generated by `pnpm asset:build`. */
export interface PieceDef {
	name: string;
	url: string;
	/** Download size in bytes, with its textures (preload progress). */
	bytes: number;
	/** Footprint in cells, [x, z] before rotation. [0, 0] for caps, which occupy no cell. */
	footprint: [number, number];
	levels: number;
	sockets: PieceSocket[];
	spawns: Vec3[];
	/** Where creatures may start (creature-* markers). */
	creatures: Vec3[];
	extracts: Vec3[];
	/** Where the rite can be initiated (rite-* markers). */
	rites: Vec3[];
	/**
	 * Where a rite's item is laid on the altar (altar-* markers: the Gloaming Chapel's, for the
	 * Pendant). Left out in hand-built test pieces.
	 */
	altars?: Vec3[];
	/** Where a loot crate may stand (crate-* markers). The server fills only some of them. */
	crates: CrateMarker[];
	/**
	 * Where a lootable of a kind may stand (lootable-<type>-<n> markers), filled like crate markers.
	 * Left out of pieces that have none.
	 */
	lootables?: LootableMarker[];
	/**
	 * Doors (door-* markers): floor centre of the doorway. At yaw 0 the room side is north (-Z);
	 * the leaves swing away from it. Every one is a door between levels (see DOORS).
	 */
	doors: CrateMarker[];
	/** Collapsed walls (rubble-* markers): the only places bricks lie, a few at each. */
	rubble: Vec3[];
	/** Ropes to climb (rope-* markers): the extraction ropes. */
	ropes: RopeMarker[];
	/** Where players can tie a rope down a drop (anchor-* markers). */
	anchors: AnchorMarker[];
	/** Candle wicks (candle-* markers): a flame at each, and the room lit by them (MapCandles). */
	candles: Vec3[];
	colliders: ColliderBox[];
	/** Gameplay volumes such as swimmable water (vol-<kind>-* boxes). */
	volumes: VolumeBox[];
	triangles: number;
}

/**
 * start: the expedition start room. major: one of the static major rooms, all placed on the
 * main route. extraction: a room with a way up to the surface, placed on the main route
 * at the end of every level but the deepest. connector: passages and minor rooms. descent: the long
 * stair from an extraction room's `gate` down to the next level. end: dead ends that close branches. cap: seals an unused opening without occupying a cell.
 */
export type PieceRole = 'start' | 'major' | 'extraction' | 'connector' | 'descent' | 'end' | 'cap';

/** Gameplay data for a piece (hand-authored, in `src/lib/content/map/kit.ts`). */
export interface KitEntry {
	role: PieceRole;
	/** Relative chance when picking among pieces of the same role. */
	weight?: number;
	/** Caps: the socket type this piece seals. */
	seals?: string;
	/** Start rooms: piece always attached to the start room's opening. */
	exit?: string;
	/** Changes level: only ever attached by its highest socket, so it always leads down. */
	descends?: boolean;
	/**
	 * Connectors: a drop that takes a rope to get down (and back up). Never on the main route,
	 * only off it, so a party without rope can't be stuck; see docs/dev/map-generation.md.
	 */
	needsRope?: boolean;
	/**
	 * Connectors: never on the main route, only on side branches (a ledge the nav grid can't climb,
	 * so creatures and the rite's things never need to get past it; map-generation.md).
	 */
	offRoute?: boolean;
	/** Major rooms: placed last on the main route, after a descent, so it is the deepest. */
	final?: boolean;
	/**
	 * Connectors: a minor room rather than a passage. Start, major and extraction pieces are rooms
	 * already. Only the map debug view uses it (docs/dev/map-generation.md#debug-grid).
	 */
	room?: boolean;
	/**
	 * What the explorer's map draws on the piece's cells (docs/dev/map.md). Stairs (`descends`
	 * or the `descent` role) and extraction rooms get theirs from those.
	 */
	sketch?: SketchSymbol;
	/** Name shown in the room banner when a player first enters it. */
	title?: string;
	/** How the space sounds (reverb, damping); default 'tunnel'. See src/lib/content/audio/ambience.ts. */
	acoustics?: Acoustics;
	/**
	 * Until its piece has lootable-* markers: what its crate markers hold, by relative weight
	 * (`crate` among them keeps some crates). A type nothing can open yet is left out. See
	 * docs/dev/lootables.md#rooms.
	 */
	lootables?: Partial<Record<LootableId, number>>;
	/**
	 * Owned by one Affliction (key into AFFLICTIONS): only generated in its maps, and its model
	 * lives in static/assets/afflictions/<id>/. Unset: shared by every map.
	 */
	affliction?: string;
}

export type Acoustics = 'tight' | 'tunnel' | 'hall' | 'vast';

/** A passage the explorer's map marks with a symbol: wet, low or tight. */
export type SketchSymbol = 'water' | 'crawl' | 'squeeze' | 'ledge';

export type MapKit = Record<string, KitEntry>;

/** One piece placed in the world. */
export interface Placement {
	piece: string;
	/** World position of the piece origin (floor level, centre of footprint). */
	position: Vec3;
	/** Quarter turns around +Y (counter-clockwise seen from above), 0-3. */
	rotation: number;
	/**
	 * Level of the map it belongs to: 0 at the top, down to the deepest (see GenerateOptions.tiers).
	 * Players see it counted from 1. The long stair belongs to the level it leads down to.
	 */
	tier: number;
}

/** A loot crate standing in the map. */
export interface CratePlacement {
	id: string;
	/** Floor centre, world space. */
	position: Vec3;
	/** Turn about +Y (radians). At 0 its back is to the north (-Z) and it opens to the south. */
	yaw: number;
	/**
	 * What kind of lootable it is (LOOTABLES: a corpse, a locked trunk, a wall niche...); absent
	 * for a crate. Only the solid ones are in the collision world.
	 */
	kind?: Exclude<LootableId, 'crate'>;
	/** The level of the map it is on (its piece's tier): what it can hold depends on it. */
	tier: number;
}

/**
 * A double door (see DOORS): between levels, at the top of each long stair, and the way into the
 * final room. Solid until opened.
 */
export interface DoorPlacement {
	id: string;
	/** The piece it stands in (stairs-deep, gloaming-chapel). */
	piece: string;
	/** Floor centre of the doorway, world space. */
	position: Vec3;
	/** Turn about +Y (radians). At 0 the room side is north (-Z) and the leaves swing south. */
	yaw: number;
	/** The level of the map it is on: for a long stair's, the one it leads down to. */
	tier: number;
}

/**
 * A false wall (docs/dev/map-generation.md#false-walls): a cap piece standing in an opening that
 * does lead on, to a side passage nothing else reaches. Solid until pried down.
 */
export interface WallPlacement extends Placement {
	/** Its id: its collision boxes carry it, like a door's (openDoor takes them away). */
	id: string;
}

export interface MapLayout {
	seed: number;
	/** The Affliction this map was generated for (its own pieces are in it); null for none. */
	affliction: string | null;
	placements: Placement[];
	/** Loot crates (see docs/dev/items.md). Solid: they are part of the collision world. */
	crates: CratePlacement[];
	/** Doors between levels (see docs/dev/map-generation.md#doors). Solid while shut. */
	doors: DoorPlacement[];
	/** False walls (map-generation.md#false-walls); none in a layout made before them. */
	walls?: WallPlacement[];
}
